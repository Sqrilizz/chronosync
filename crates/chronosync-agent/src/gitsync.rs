use std::fs::{OpenOptions, create_dir_all};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use chrono::{DateTime, Utc};

pub fn default_repo_dir() -> PathBuf {
    if let Ok(home) = std::env::var("HOME") {
        PathBuf::from(home)
            .join(".local")
            .join("share")
            .join("chronosync")
            .join("activity-repo")
    } else {
        PathBuf::from(".chronosync-activity-repo")
    }
}

pub fn ensure_repo(repo_url: &str, repo_dir: &Path) -> Result<()> {
    if repo_dir.join(".git").exists() {
        return Ok(());
    }

    if let Some(parent) = repo_dir.parent() {
        create_dir_all(parent)?;
    }

    let status = Command::new("git")
        .args(["clone", repo_url])
        .arg(repo_dir)
        .status()
        .context("Failed to run git clone")?;

    if !status.success() {
        bail!("git clone failed with exit status: {:?}", status.code());
    }

    Ok(())
}

pub fn commit_and_push_activity(
    repo_url: &str,
    custom_dir: Option<&Path>,
    project: &str,
    file: Option<&str>,
    language: Option<&str>,
    timestamp: i64,
) -> Result<String> {
    let repo_dir = match custom_dir {
        Some(d) => d.to_path_buf(),
        None => default_repo_dir(),
    };

    ensure_repo(repo_url, &repo_dir)?;

    let activity_dir = repo_dir.join("activity");
    create_dir_all(&activity_dir)?;

    let date_str = match DateTime::from_timestamp(timestamp, 0) {
        Some(dt) => dt.format("%Y-%m-%d").to_string(),
        None => Utc::now().format("%Y-%m-%d").to_string(),
    };

    let time_str = match DateTime::from_timestamp(timestamp, 0) {
        Some(dt) => dt.format("%H:%M:%S UTC").to_string(),
        None => Utc::now().format("%H:%M:%S UTC").to_string(),
    };

    let log_file = activity_dir.join("log.jsonl");
    let mut file_handle = OpenOptions::new()
        .create(true)
        .append(true)
        .open(&log_file)?;

    let record = serde_json::json!({
        "timestamp": timestamp,
        "date": date_str,
        "time": time_str,
        "project": project,
        "file": file,
        "language": language,
    });

    writeln!(file_handle, "{}", record)?;

    let daily_summary_file = activity_dir.join(format!("{}.md", date_str));
    let mut summary_handle = OpenOptions::new()
        .create(true)
        .append(true)
        .open(&daily_summary_file)?;

    writeln!(
        summary_handle,
        "- `{}` | project: **{}** | file: `{}` | lang: `{}`",
        time_str,
        project,
        file.unwrap_or("-"),
        language.unwrap_or("-")
    )?;

    let readme_file = repo_dir.join("README.md");
    let readme_content = format!(
        "# chronosync-activity\n\nAutomated developer activity commits generated by [chronosync](https://github.com/Sqrilizz/chronosync).\n\n- **Last Activity:** {} {}\n- **Project:** {}\n- **Language:** {}\n",
        date_str,
        time_str,
        project,
        language.unwrap_or("none")
    );
    std::fs::write(&readme_file, readme_content)?;

    let add_status = Command::new("git")
        .current_dir(&repo_dir)
        .args(["add", "."])
        .status()
        .context("Failed to run git add")?;

    if !add_status.success() {
        bail!("git add failed");
    }

    let commit_message = format!("activity: {} on {} ({})", project, date_str, time_str);
    let commit_status = Command::new("git")
        .current_dir(&repo_dir)
        .args(["commit", "-m", &commit_message])
        .status()
        .context("Failed to run git commit")?;

    if !commit_status.success() {
        return Ok("Nothing to commit (clean working tree)".to_string());
    }

    let push_status = Command::new("git")
        .current_dir(&repo_dir)
        .args(["push", "origin", "HEAD"])
        .status()
        .context("Failed to run git push")?;

    if !push_status.success() {
        bail!("git push failed with exit status: {:?}", push_status.code());
    }

    Ok(commit_message)
}
